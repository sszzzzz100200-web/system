import random

@app.route('/api/negotiate', methods=['POST'])
def negotiate():
    data = request.json
    msg = data.get('message', '').lower()
    
    # قائمة ردود متنوعة للمساعد لكسر التكرار
    responses = {
        "start": [
            "🚀 جاري تفعيل محرك البحث الآن... سأستخرج لك بيانات حصرية لم تتوفر لأحد قبلك. نعتمد؟",
            "أبشر، بدأت فعلياً بجمع بيانات الموردين والأسعار. التقرير المتقدم (250 ريال) سيكون بين يديك فور إتمام الدفع.",
            "فهمتك، لنضيع الوقت في الكلام وننتقل للنتائج. جاري إطلاق 10 زواحف الآن لجمع ذهب السوق."
        ],
        "price": [
            "شوف يا غالي، التقرير يفتح لك أبواب أرباح كانت مخفية عنك، الـ 250 ريال هي استثمار في مشروعك وليست مجرد تكلفة.",
            "الأسعار ثابتة ومنافسة جداً: 150 للأساسي، و250 للمتقدم. وش اللي يناسب ميزانيتك الحالية؟",
            "السعر هو أقل ما يمكن مقابل جودة البيانات التي سأعطيك إياها. هل نعتمد الـ 250 ونبدأ العمل؟"
        ]
    }

    # منطق اختيار الرد بذكاء
    if any(word in msg for word in ["انطلق", "ابدأ", "جيب", "تحليلات", "نتائج"]):
        reply = random.choice(responses["start"]) + f" (التحويل على PayPal: {STORE_CONFIG['paypal_email']})"
    elif any(word in msg for word in ["غالي", "سعر", "بكم", "خصم"]):
        reply = random.choice(responses["price"])
    else:
        reply = "أنا معك، اسمعك. تبي التقرير الأساسي (150) أو الشامل (250)؟ القرار عندك."
        
    return jsonify({"reply": reply})
